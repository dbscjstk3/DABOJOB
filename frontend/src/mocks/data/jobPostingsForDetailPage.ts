// 기존 호환성을 위한 함수들 (사용하지 않음)
export const jobPostingMap: Record<number, JobPostingResponse[]> = {};

export const getJobPostingsByDate = (day: number): JobPostingResponse[] => {
  return jobPostingMap[day] || [];
};

export const getJobPostingsByExpirationDate = (
  day: number,
  year: number,
  month: number,
): JobPostingResponse[] => {
  return getAllJobPostings().filter((jp) => {
    const d = new Date(jp.deadlineDate);
    return d.getDate() === day && d.getFullYear() === year && d.getMonth() === month;
  });
};
