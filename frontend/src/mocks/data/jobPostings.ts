// 검색 함수
export function searchJobPostings(searchQuery: string, page: number = 0, size: number = 20) {
  const query = searchQuery.toLowerCase().trim();

  // 검색어로 필터링
  let filtered = mockJobPostings;
  if (query) {
    filtered = mockJobPostings.filter(
      (job) =>
        job.companyName.toLowerCase().includes(query) ||
        job.title.toLowerCase().includes(query) ||
        job.jobSectorName.toLowerCase().includes(query) ||
        job.jobSectorCategory.toLowerCase().includes(query),
    );
  }

  // 페이지네이션
  const totalElements = filtered.length;
  const totalPages = Math.ceil(totalElements / size);
  const start = page * size;
  const end = start + size;
  const content = filtered.slice(start, end);

  return {
    content,
    pageable: {
      pageNumber: page,
      pageSize: size,
      sort: {
        empty: false,
        sorted: true,
        unsorted: false,
      },
      offset: start,
      paged: true,
      unpaged: false,
    },
    last: page >= totalPages - 1,
    totalElements,
    totalPages,
    size,
    number: page,
    sort: {
      empty: false,
      sorted: true,
      unsorted: false,
    },
    first: page === 0,
    numberOfElements: content.length,
    empty: content.length === 0,
  };
}
